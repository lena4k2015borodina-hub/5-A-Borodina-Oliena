age = int(input('Скільки Вам років? '))

if age > 18:
    n = age - 18
    print('Ви можете водити автомобіль вже', n, 'років')
elif age == 18:
    print('Ви вже маєте право керувати автомобілем')
else:
    r = 18 - age
    print('Ваш вік не дозволяє вам керувати автомобілем, доведеться зачекати ще', r, 'років')